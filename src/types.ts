// ============================================================================
// Coverage and Matrix Types
// ============================================================================

/**
 * Coverage report for traceability analysis
 */
export interface CoverageReport {
  totalRequirements: number;
  requirementsWithImplementation: number;
  requirementsWithTests: number;
  implementationCoverage: number;
  testCoverage: number;
  // Design coverage metrics
  totalDesigns?: number;
  designsWithImplementation?: number;
  designCoverage?: number;
  requirementsAddressedByDesign?: number;
  requirementCoverageByDesign?: number;
}

/**
 * Row data for requirement matrices
 */
export interface RequirementRow {
  id: string;
  title: string;
  implementations: string[];
  tests: string[];
}

/**
 * Row data for design matrices
 */
export interface DesignRow {
  id: string;
  title: string;
  implementations: string[];
  tests: string[];
  depth?: number;
}

/**
 * Detailed requirement information
 */
export interface RequirementDetail {
  id: string;
  title: string;
  status: string;
  satisfiedBy: string[];
  implementedBy: string[];
  testedBy: string[];
  verifiedBy: string[];
  documentedBy: string[];
}

/**
 * Detailed implementation information
 */
export interface ImplementationDetail {
  id: string;
  title: string;
  satisfies: string[];
  testedBy: string[];
}

/**
 * Detailed test information
 */
export interface TestDetail {
  id: string;
  title: string;
  verifies: string[];
  tests: string[];
}

/**
 * Traceability matrix data structure
 */
export interface TraceabilityMatrix {
  type: string;
  coverage: CoverageReport;
  requirements: RequirementRow[];
  generatedAt: string;
}

/**
 * Design traceability matrix data structure
 */
export interface DesignTraceabilityMatrix {
  type: string;
  coverage: CoverageReport;
  designs: DesignRow[];
  generatedAt: string;
}

/**
 * Detailed traceability matrix with all information
 */
export interface DetailedTraceabilityMatrix {
  type: string;
  coverage: CoverageReport;
  uncoveredRequirements: string[];
  requirements: RequirementDetail[];
  implementations: ImplementationDetail[];
  tests: TestDetail[];
  generatedAt: string;
}

// ============================================================================
// Type Guards
// ============================================================================

/**
 * Check if a relationship type is primary
 */
export function isPrimaryRelationshipType(
  type: string,
): type is PrimaryRelationshipType {
  return type in INVERSE_MAP;
}

/**
 * Check if a relationship type is inverse
 */
export function isInverseRelationshipType(
  type: string,
): type is InverseRelationshipType {
  return type in PRIMARY_MAP;
}

